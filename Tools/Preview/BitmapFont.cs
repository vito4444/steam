        /// <summary>Draws text at 1x scale or larger. Returns the width consumed in pixels.</summary>
        public static int Draw(Raster raster, int x, int y, string text, RgbColor color, int scale = 1)
        {
            if (string.IsNullOrEmpty(text)) return 0;

            int cursor = x;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (c >= 'a' && c <= 'z' && !Glyphs.ContainsKey(c)) c = (char)(c - 'a' + 'A');
                if (!Glyphs.TryGetValue(c, out var glyph)) glyph = Glyphs['?'];

                for (int row = 0; row < GlyphHeight; row++)
                {
                    string line = glyph[row];
                    for (int col = 0; col < GlyphWidth; col++)
                    {
                        if (line[col] != '#') continue;
                        raster.FillRect(cursor + col * scale, y + row * scale, scale, scale, color);
                    }
                }

                cursor += Advance * scale;
            }

            return cursor - x;
        }

        public static int MeasureWidth(string text, int scale = 1)
            => string.IsNullOrEmpty(text) ? 0 : text.Length * Advance * scale;

        /// <summary>Draws text with a one pixel dark outline so it stays readable over any background.</summary>
        public static int DrawOutlined(Raster raster, int x, int y, string text, RgbColor color, RgbColor outline, int scale = 1)
        {
            for (int dy = -1; dy <= 1; dy++)
            {
                for (int dx = -1; dx <= 1; dx++)
                {
                    if (dx == 0 && dy == 0) continue;
                    Draw(raster, x + dx * scale, y + dy * scale, text, outline, scale);
                }
            }
            return Draw(raster, x, y, text, color, scale);
        }
